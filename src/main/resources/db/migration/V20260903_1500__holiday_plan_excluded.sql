-- 학습계획 입력 차단일 (API_GAPS 5-11)
--
-- ■ 무엇이 틀렸나
--
-- 학습계획 현황의 missingDays 가 "조회일수 − 계획쓴날"이었다. 조회일수가 달력 일수라
-- 휴원일·일요일이 전부 미작성으로 잡히고, 그러면 휴원 주간마다 전교생이 미작성자로 떠서
-- 경고가 무의미해진다. 이 화면은 손이 필요한 학생을 찾는 곳이라 그게 곧 화면의 실패다.
--
-- ■ 왜 holiday 에 두나 (별도 테이블이 아니라)
--
-- 별도 테이블이면 같은 날(예: 개원기념일 휴원)을 두 군데 등록하게 되고, 한쪽만 넣은 날이
-- 반드시 생긴다. 날짜 마스터는 하나로 두고 축을 늘린다.
--
-- ■ 왜 기존 휴일을 그대로 쓰지 않나
--
-- holiday 는 급식 가능일 판정용이라 법정공휴일이 전부 들어 있는데, 이 학원은 법정공휴일에도
-- 운영한다(교습일수에서 빼는 날은 설날·추석 당일뿐이다 — 2026-08-26 확정).
-- 공휴일을 그대로 차단일로 쓰면 운영한 날의 미작성이 통째로 사라진다.
-- "급식 쉬는 날"과 "학습계획을 안 써도 되는 날"은 다른 개념이다.
--
-- ■ 기본값이 FALSE 인 이유
--
-- 켜기 전까지는 지금과 값이 같다. 기본을 TRUE 로 두면 마이그레이션을 적용하는 순간
-- 전 지점의 미작성일 수가 한꺼번에 줄어드는데, 아무도 그걸 의도한 적이 없다.
ALTER TABLE holiday
    ADD COLUMN plan_excluded BOOLEAN NOT NULL DEFAULT FALSE;

COMMENT ON COLUMN holiday.plan_excluded IS
    '학습계획 미작성 집계에서 제외하는 날(휴원일 등). 급식 판정과는 별개 축이다';
