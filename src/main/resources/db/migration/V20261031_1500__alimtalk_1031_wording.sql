-- 알림톡 수정안 (디랩 1031) — 승인 요청 문구 · 등록비 학생별 발송
--
-- ★ V20261026120000 을 고치지 않는다. 한 번 적용된 마이그레이션은 체크섬이 어긋나
--   기동이 실패한다(CLAUDE.md §2). 바꿀 것은 새 파일로 쓴다.
--
-- ⚠️ 본문이 카카오 승인본과 한 글자라도 다르면 발송이 실패한다. 아래 문구는
--   ★ 아직 심사 전이다 — 재심사가 통과할 때까지 발송은 지금 승인된 문구로 나간다.
--   그래서 review_status 는 건드리지 않는다(승인됨으로 보이면 발송이 거절된다).

-- ── 1. 승인 요청 접수 (UM_8240) ────────────────────────────────
--
-- ★ 「승인해주세요」는 띄어 쓰지 않는다 — 디랩 원문 그대로다.
--   첫 줄은 그대로 둔다.

UPDATE notification_template
   SET body_template = '[DLab] {studentName} 학생이 {requestType}을 신청하였습니다.
{requestedAt}부터 {timeoutMinutes}분 이내에 승인해주세요.'
 WHERE event_code = 'APPROVAL_REQUEST_CREATED';

-- ── 2. 등록비 안내를 학생별 발송으로 되돌린다 ──────────────────
--
-- ★★ 10/23 에 「전원 공통 안내」로 바꿨다(student_specific = FALSE). 그때는 디랩
--    문구에 학생명이 없어서 ★ 학부모당 한 통으로 묶는 것이 맞았다.
--
-- ★ 10/31 수정안에 ★ #{학생명} 이 다시 들어왔다. 두 안(디랩안·우리 대안) 모두
--   학생명을 쓴다. 그래서 ★ 학생마다 한 건씩 보낸다 — 형제가 있으면 따로 간다.
--
-- ⚠️ 묶어서 보내면 ★ 한 자녀의 안내가 사라진다. 등록 기간은 학생마다 같아도
--    「누구의 등록인가」가 문장에 들어가므로 더 이상 공통 안내가 아니다.
--
-- ⚠️ 급식 마감(MEAL_APPLY_DEADLINE)은 ★ 그대로 공통이다 — 그 문구에는 학생명이
--    없고, 넣으면 문장이 어색해진다(CLAUDE.md 알림 템플릿 원칙).

-- ★★ 문구 확정도 함께 푼다 — 그러지 않으면 ★ 행이 모순 상태가 된다.
--
--    NotificationTemplateService 가 「확정 && 학생별 && 본문에 {studentName} 없음」을
--    ★ 거부한다. 지금 본문은 '[DLab] {기간} {월} 등록기간입니다.' 로 ★ 학생명이 없다
--    (10/23 공통 안내로 바꿀 때 뺐다).
--
-- ⚠️ 그대로 TRUE 로 두면 ★ 다음에 이 템플릿을 고치려는 순간 저장이 거부된다 —
--    「왜 수정이 안 되지」로 보이고 원인이 이 마이그레이션에 있다.
--
-- ★ 발송은 어차피 막혀 있다 — 알림톡은 심사 통과(APPROVED)가 있어야 나가고
--   지금 review_status 가 DRAFT 다(카카오 UM_8514 반려분). 즉 ★ 잃는 것이 없다.
--
-- ★ 디랩 문구 회신이 오면 ★ 본문과 확정을 ★ 같이 넣는다(새 마이그레이션).
UPDATE notification_template
   SET student_specific = TRUE,
       content_confirmed = FALSE
 WHERE event_code = 'TUITION_REGISTRATION_NOTICE';
