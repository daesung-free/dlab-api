-- V20260807_1730: 교시에 의무/자율 구분을 더한다
--
-- ★ 실제 교시표(2026-08-07 수령)에 "의무자습"과 "자율선택자습"이 갈려 있다.
--   이 구분이 없으면 두 군데가 틀어진다.
--
-- ① 주말에 지각이 찍힌다
--    주말·공휴일도 교시는 그대로 있다(9교시만 미운영). 전부 자율선택자습일 뿐이다.
--    "교시 유무"로 자율등원일을 판정하면 주말이 운영일로 잡혀, 등원 기준 시각을
--    넘긴 학생이 전부 지각으로 남는다. 자율인데 지각이 있을 수 없다.
--
-- ② 하원이 안 찍힌다
--    평일 마지막 교시는 9교시(23:50)지만 8·9교시는 자율선택자습이다.
--    의무자습은 7교시(21:50)에 끝난다. 하원 경계를 "마지막 교시 종료"로 잡으면
--    22:00에 나가는 학생이 하원이 아니라 130("승인 내역이 없습니다")을 받는다.
--    실제로 동탄에서 21:50 이후 태깅이 문제가 된 것도 이 경계 때문이다.
--
-- → 판정 기준을 "교시가 있는가"에서 "의무 교시가 있는가"로 바꾼다.
--
-- 기존 행은 TRUE로 둔다. 지금 데이터가 없고, 있더라도 의무로 보는 쪽이
-- 지각·하원 판정에서 더 보수적이다(놓치는 것보다 낫다).

ALTER TABLE period_master
    ADD COLUMN mandatory BOOLEAN NOT NULL DEFAULT TRUE;

COMMENT ON COLUMN period_master.mandatory IS
    '의무자습 여부. 지각 판정과 하원 경계가 이 값으로 갈린다 — 자율만 있는 날은 지각이 없다';
