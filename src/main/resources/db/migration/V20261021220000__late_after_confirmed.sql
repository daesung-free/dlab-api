-- 지각 기준시각 확정 — 전 지점 공통 07:50 (디랩 1021 알림톡 회신).
--
-- 회신 원문: "지각/결석 기준시간 변동 없으며 지각 기준시각(07시50분)은 전 지점 공통 입니다."
--
-- ★★ 왜 기본값을 박는가 — 폴백이 이제 틀렸다
--   V20261020100000 에서 late_after 를 nullable 로 두고, 비면 attendance_deadline 으로
--   떨어지게 했다. 그때는 그게 맞았다 —
--     "07:50 을 기본값으로 박으면 값이 안 들어온 지점에서 08시에 오는 학생이 전부
--      지각으로 찍힌다. 디랩이 준 07:50·08:20 은 아직 한 건도 들어오지 않았고
--      11개 지점이 전부 09:00 이다. 모르면 추측값을 쓰지 않는다."
--
--   이제 07:50 은 추측값이 아니라 디랩이 준 확정값이다. 폴백을 그대로 두면
--   late_after 가 빈 지점에서 지각 기준이 09:00 이 되어
--   ⚠️ 07:55 에 온 학생이 「정상 등원」으로 찍히고 학부모는 지각 알림을 못 받는다.
--   오류가 나지 않고 조용히 틀린다.
--
-- ★ 컬럼은 지우지 않는다. 지금은 공통이지만 지점별로 갈릴 수 있고, 그때 컬럼이 없으면
--   마이그레이션을 다시 써야 한다. 값만 채운다.
--
-- ⚠️ 등원 기준시각(attendance_deadline)은 건드리지 않는다 — 다른 축이고
--   디랩이 1019 에 "지점마다 정한 등원 기준시각"으로 답했다. 11개 지점 실제 값은
--   아직 받지 못했고 전 지점 09:00 기본값이다(§4 · 컷오버 체크리스트).

UPDATE academy
SET late_after = TIME '07:50',
    updated_at = now()
WHERE late_after IS NULL
  AND is_deleted = FALSE;

-- 신규 지점도 07:50 으로 들어온다 — 지점을 추가하고 값을 빠뜨리는 경로를 막는다
ALTER TABLE academy
    ALTER COLUMN late_after SET DEFAULT TIME '07:50';

COMMENT ON COLUMN academy.late_after IS
    '지각 기준시각. 전 지점 공통 07:50 (디랩 2026-10-21 확정). '
    '★ attendance_deadline 과 다른 축이다 — 한 칸으로 두면 기준시각이 08:20 인 지점에서 '
    '07:55 에 온 학생이 출결상 정상 등원인데 학부모에게는 지각 알림이 간다';

-- ─────────────────────────────────────────────────────────────
-- 결석(등원) 기준시각 — 전 지점 08:20
--
-- ★ 08:20 은 추측이 아니다. 1019 문서가 "디랩이 준 시각이 두 개다 —
--   지각 07:50 이후 태깅부터 / 결석 08:20 (6번, 이전 회신)" 으로 적고 있다.
--   오늘 회신의 "지각/결석 기준시간 변동 없으며" 가 그 둘을 가리킨다.
--
-- ⚠️ 지금까지 전 지점 09:00 이었다 — 그건 디랩이 준 어느 값도 아니고 우리 기본값이다.
--   그래서 미등원 알림이 40분 늦게 나가고 있었다.
--
-- ⚠️ 디랩은 결석 기준이 전 지점 공통인지 말하지 않았다. 1019 에는
--   "지점마다 정한 등원 기준시각에 맞춰 돌도록" 이라고 했고, 오늘은 지각만
--   "전 지점 공통" 이라고 명시했다. → 지점별로 다른 값이 올 수 있다.
--   전 지점 동일하게 넣는 것은 운영 판단이며(2026-10-21), 지점별 값이 오면
--   그 지점만 고친다. 컬럼이 지점별이라 마이그레이션 없이 데이터로 받는다.
UPDATE academy
SET attendance_deadline = TIME '08:20',
    updated_at          = now()
WHERE is_deleted = FALSE
  AND attendance_deadline = TIME '09:00';   -- ★ 기본값으로 남아 있는 지점만

COMMENT ON COLUMN academy.attendance_deadline IS
    '등원(결석) 기준시각. 이 시각까지 태깅이 없으면 미등원 알림이 나가고 결석으로 확정된다. '
    '전 지점 08:20 (디랩 회신, 2026-10-21 전 지점 동일 적용). '
    '★ late_after(지각 07:50)와 다른 축이다 — 섞으면 07:55 도착이 정상 등원인데 지각 알림이 간다';
