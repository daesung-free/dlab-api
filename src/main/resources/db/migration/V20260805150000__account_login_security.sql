-- ==========================================================================
-- 로그인 보안 (앱 요구사항 A-1 · 관리자 F-4.12-1)
--
--   "임시 비밀번호 최초 로그인 시 변경 강제, 비밀번호 정책·로그인 실패 5회 계정 잠금"
--
-- ⚠️ A-1이 참조하는 `4시트 NF-05·NF-06`은 두 시트 어디에도 존재하지 않는다(2026-08-05 확인).
--    끊긴 참조라 아래 값은 A-1 본문의 "5회"와 F-4.12-1의 "잠금 해제"(관리자 기능)에서
--    역산한 것이다. 정책이 확정되면 PasswordPolicy 상수만 바꾸면 되도록 코드에 분리해뒀다.
-- ==========================================================================


-- --------------------------------------------------------------------------
-- 1. 임시 비밀번호 → 최초 로그인 시 변경 강제
-- --------------------------------------------------------------------------

-- ★ 토큰을 안 주는 방식이 아니다. 로그인은 시켜주되 비밀번호 변경 외의 API를 막는다 —
--   토큰 없이 비밀번호를 바꾸게 하려면 별도 인증 수단을 또 만들어야 한다.
ALTER TABLE account ADD COLUMN must_change_password BOOLEAN NOT NULL DEFAULT FALSE;

COMMENT ON COLUMN account.must_change_password IS
    '임시 비밀번호 상태. TRUE면 비밀번호 변경 외 모든 API가 차단된다(A-1 "최초 로그인 시 변경 강제").';

-- 정책이 "90일마다 변경" 같은 형태로 확정될 때 필요하다. 지금은 기록만 한다.
ALTER TABLE account ADD COLUMN password_changed_at TIMESTAMPTZ;

COMMENT ON COLUMN account.password_changed_at IS
    '마지막 비밀번호 변경 시각. 만료 정책(NF-05 미확보) 확정 시 판정 기준이 된다.';


-- --------------------------------------------------------------------------
-- 2. 로그인 실패 잠금
-- --------------------------------------------------------------------------

-- ★ status='SUSPENDED'로 처리하지 않는다.
--   SUSPENDED는 관리자가 의도적으로 정지시킨 상태이고, 잠금은 실패 누적으로 자동 발생한다.
--   같은 칸에 넣으면 잠금 해제 시 "원래 SUSPENDED였는지 잠금이었는지"를 알 수 없어
--   정지된 계정이 잠금 해제만으로 되살아난다.
ALTER TABLE account ADD COLUMN locked_at TIMESTAMPTZ;

COMMENT ON COLUMN account.locked_at IS
    '로그인 실패 누적 잠금 시각. NULL이면 잠기지 않음. 자동 해제는 없고 관리자가 푼다(F-4.12-1).';

-- 관리자 화면(F-4.12-1)이 "잠긴 계정 목록"을 뽑는다. 잠긴 계정은 전체 대비 극소수라 부분 인덱스가 맞다.
CREATE INDEX idx_account_locked ON account (locked_at) WHERE locked_at IS NOT NULL;


-- --------------------------------------------------------------------------
-- 3. 기존 계정 보정
-- --------------------------------------------------------------------------

-- 이미 쓰이던 계정은 임시 비밀번호가 아니므로 변경 강제 대상이 아니다(기본값 FALSE 그대로).
-- 다만 마지막 변경 시각이 비어 있으면 만료 정책 도입 시 전원이 즉시 만료로 걸린다 —
-- 생성 시각으로 채워둔다.
UPDATE account SET password_changed_at = created_at WHERE password_hash IS NOT NULL;
