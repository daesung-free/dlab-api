-- ★★ 왜 필요한가 — **단말이 꺼져 있으면 이탈 기록이 「0」이 아니라 「비는 것」**이다.
--   지금은 좌석표가 비었을 때 「아무도 안 나갔다」와 「단말이 죽었다」를 가를 수 없다.
--
-- ⚠️ CLAUDE.md §3 에 같은 경고가 있다 — 키오스크는 **우리 장애를 알려주지 않는다.**
--   급식 조회가 실패하면 전원 통과시키는 관대한 폴백이 있어 **우리 서버가 죽어도 화면은
--   정상으로 보인다.** 그래서 우리 쪽에서 따로 감시해야 한다.
--
-- ★ 하트비트가 없다. 키오스크는 주기적 신호를 보내지 않으므로 **/kiosk/** 를 마지막으로
--   부른 시각**을 쓴다. 정확한 생존 신호는 아니지만 「오늘 한 번도 안 불렀다」는 확실히
--   드러난다 — 지금은 그것조차 못 본다.
--
-- ★ Redis 가 아니라 DB 에 남긴다. 토큰처럼 잃어도 되는 값이 아니라 **운영 판단의 근거**라
--   재시작에 사라지면 그 판단이 틀려진다.
--
-- ⚠️ 지점당 단말 1대 전제다(2026-10-26 확인). /auth/token 이 acad_cd + client_id 로
--   인증하고 **요청에 단말 식별자가 없어** 한 지점에 2대가 생기면 구분할 수 없다.
--   그때는 키오스크 쪽이 식별자를 보내게 고쳐야 한다(당사 개발이라 가능하다).

