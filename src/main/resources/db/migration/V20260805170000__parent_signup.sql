-- 학부모 가입 (앱 요구사항 A-2)
--
--   "PARENT_LINKED = 학생 고유ID 입력 + 학부모 휴대폰 인증으로 학부모 계정 연동(최대 1인)"
--
-- 학부모는 승인 절차가 없다(학생만 승인제). 휴대폰 인증과 학생 고유ID만 맞으면 즉시 ACTIVE.
-- ==========================================================================


-- --------------------------------------------------------------------------
-- 1. 학생당 학부모는 최대 1인
-- --------------------------------------------------------------------------

-- I-12 ▷[0803] "학부모 최대 1인 확정". V1의 PK가 (student_id, guardian_id)라
-- 한 학생에 여러 학부모가 붙을 수 있었다 — 그러면 승인 라우팅에서 "누가 승인자인가"가
-- 다시 모호해진다. 그 모호성을 없애려고 확정한 것이므로 제약으로 못 박는다.
--
-- ⚠️ 반대 방향은 막지 않는다 — 학부모 1명이 자녀 여러 명을 갖는 건 정상이다
--    (계정 1개 + 자녀 N + 앱 내 자녀전환, CLAUDE.md §3).
CREATE UNIQUE INDEX uq_guardian_link_student ON student_guardian_link (student_id);

COMMENT ON INDEX uq_guardian_link_student IS
    '학생당 학부모 최대 1인(I-12 0803 확정). 자녀 여러 명은 허용된다 — 방향이 반대다.';

-- relation_order는 학부모가 여럿일 때 승인 순서를 정하려던 컬럼이다.
-- 1인 확정으로 쓸 일이 없어졌지만 지우지 않는다 — 되돌아갈 때 값이 필요하고,
-- 이 항목은 이미 여러 번 뒤집혔다.
COMMENT ON COLUMN student_guardian_link.relation_order IS
    '학부모 다인 시절의 승인 순서. 최대 1인 확정(0803)으로 현재는 항상 1이다.';
