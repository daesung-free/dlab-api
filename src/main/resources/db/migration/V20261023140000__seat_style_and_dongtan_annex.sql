-- ==========================================================================
-- 1. 좌석형태 — seat_master.seat_style
-- ==========================================================================
--
-- ★ 왜 기존 SeatType {GENERAL, SINGLE} 을 쓰지 않는가
--   그건 좌석이 아니라 **교습비**에 붙어 있고(TuitionPrice.seat_type) 2종이라
--   교실형·집중형을 가르지 못한다. 전 지점 2,140석이
--   교실형 1,637 · 집중형 449 · 1인실 54 로 갈린다.
--
-- ★ 교습비와 잇지 않는다
--   「1인실 좌석에 앉으면 교습비가 1인실 단가」로 연결하면 자리를 옮길 때마다
--   청구가 흔들린다. 두 값이 어긋나면 화면에서 알려 주기만 한다.
--
-- ★ 기본값이 CLASSROOM 인 이유
--   1,637석이 교실형이라 가장 적은 수를 고치면 된다. 다만 **지금 들어 있는 좌석이
--   전부 교실형이 되는 것은 아니다** — 실제 형태는 시트2 범위대로 덮어쓴다
--   (PATCH /api/v1/admin/seats/masters/styles). 적재는 이 마이그레이션의 일이 아니다.

ALTER TABLE seat_master
    ADD COLUMN seat_style VARCHAR(20) NOT NULL DEFAULT 'CLASSROOM';

ALTER TABLE seat_master
    ADD CONSTRAINT ck_seat_master_style
        CHECK (seat_style IN ('CLASSROOM', 'FOCUS', 'SINGLE_ROOM'));

COMMENT ON COLUMN seat_master.seat_style IS
    '좌석형태. CLASSROOM 교실형 / FOCUS 집중형 / SINGLE_ROOM 1인실. '
    '교습비(SeatType)와는 다른 축이다 — 이 값으로 청구가 갈리지 않는다';


-- ==========================================================================
-- 2. 동탄 별관(관) 행
-- ==========================================================================
--
-- V20260914100000 이 지점마다 MAIN 만 만들고 별관은
-- "어느 것이 별관인지 번호만 보고 단정할 수 없다 — 컷오버 체크리스트 항목이다"
-- 라며 남겨 뒀다. 2026-10-22 답변으로 **동탄 별관 A·B·C 가 확정**됐으므로 닫는다.
--
-- ★★ seat_cd_offset 은 만든 뒤 바꿀 수 없다
--    이 값이 좌석 등록 시점에 kiosk_seat_cd 에 **이미 반영돼 저장**되기 때문이다.
--    나중에 바꾸면 그 관의 기존 좌석들과 어긋나, 화면은 멀쩡한데 단말에서만 자리가
--    밀린다. 그래서 **만드는 지금 1000 을 넣는다** — 별관이 1000번대로 운영돼 온
--    값 그대로라(1번 → 1001번) 기존 운영과 번호가 같다.
--
-- ★ 동탄(acad_cd = '33') 에만 만든다
--   다른 지점에 만들면 좌석이 하나도 없는 빈 관이 화면에 뜬다.
--
-- ★ 구역을 여기로 옮기지 않는다
--   별관 A·B·C 구역 이동과 2,140석 적재는 배치표를 눈으로 읽어야 하는 별개 작업이다.
--   그릇만 만든다.
--
-- created_by 0 은 시스템 계정이다(CLAUDE.md §7).
-- NOT EXISTS 는 지점 시드가 없는 환경(테스트·빈 DB)에서 0건으로 지나가게 하고,
-- 이미 손으로 만들어 둔 별관이 있을 때 중복을 막는다.

INSERT INTO building (academy_id, code, name, sort_order, seat_cd_offset, created_by)
SELECT a.id, 'ANNEX', '별관', 1, 1000, 0
FROM academy a
WHERE a.acad_cd = '33'
  AND NOT EXISTS (
      SELECT 1 FROM building b
       WHERE b.academy_id = a.id
         AND b.code = 'ANNEX'
         AND b.is_deleted = FALSE
  );
