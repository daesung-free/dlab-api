package com.dlab.domain.facility.entity;

/**
 * 좌석형태 — <b>그 자리가 어떤 모양인가</b>.
 *
 * <h2>★ {@code com.dlab.domain.payment.entity.SeatType} 과 다른 축이다</h2>
 * {@code SeatType {GENERAL, SINGLE}} 은 <b>교습비에 붙어 있다</b>("얼마짜리 상품인가").
 * 여기는 좌석 자체의 모양이라 전 지점 2,140석이 교실형 1,637 · 집중형 449 · 1인실 54 로
 * 갈린다 — 2종으로는 교실형·집중형을 가를 수 없다.
 *
 * <h2>★ 교습비와 잇지 않는다</h2>
 * 「1인실 좌석에 앉으면 교습비가 1인실 단가」로 연결하면 <b>자리를 옮길 때마다 청구가
 * 흔들린다.</b> 두 값이 어긋나면 화면에서 알려 주기만 하고 막지 않는다
 * ({@code SeatType} 주석의 판단 그대로다).
 *
 * <h2>한 구역 안에 섞여 있다</h2>
 * 구역 단위가 아니라 <b>번호 범위 단위</b>다(디랩 2026-10-22 답변). 광명 C 구역 87석이
 * 교실형 213~253·268~283 / 집중형 201~212·254~267·284~287 처럼 최대 3개 구간으로
 * 쪼개진다 — 그래서 격자 등록이 <b>범위 목록</b>을 받는다.
 */
public enum SeatStyle {

    /** 교실형. 가장 많고, 형태를 안 보냈을 때의 기본값이다. */
    CLASSROOM,

    /** 집중형(독서실형 칸막이석). */
    FOCUS,

    /** 1인실. <b>분당·목동·대구에만 있다</b>(2026-10-22 확정 — 송파는 아니다). */
    SINGLE_ROOM
}
