package com.dlab.domain.penalty.entity;

/**
 * 자동부여 트리거 종류.
 *
 * <h2>⚠️ 「순찰 트리거를 넣지 말 것」은 <b>낡은 지침이었다</b></h2>
 * 전에 이 자리에 <b>「{@code PATROL_SLEEP_2}(2회 연속 졸음)를 넣지 말 것 — 사감 순찰이
 * 0803에 전면 폐기되면서 이 트리거도 삭제됐다」</b> 가 적혀 있었다.
 *
 * <p>★ <b>순찰은 2026-10-13 에 다시 들어왔고</b>(피드백 1-3), 디랩이 1029 벌점 시트에
 * <b>졸음 벌점을 명시적으로 요청</b>했다. 그래서 {@link #PATROL} 을 더했다.
 *
 * <p>★ 다만 <b>순공시간 산출식에서 순찰 기준이 빠진 것은 그대로</b>다 — 그건 별개 축이다.
 */
public enum PenaltyTriggerType {

    /** 출결 태깅 결과(지각·결석·조퇴 등). */
    ATTENDANCE,

    /** 데일리 루틴 결과(미제출·결시 등). */
    DAILY_ROUTINE,

    /**
     * ★★ 순찰에서 <b>졸음({@code SLEEP})이 임계값만큼 쌓였을 때</b> (디랩 1029 4-6).
     *
     * <p>시트 원문: <b>「교시별로 학생 취침을 3회 체크하면 자동 벌점 부여」</b>
     *
     * <p>★ 조건값은 {@code PatrolMark} 이름이다 — 지금은 {@code SLEEP} 하나다.
     * ★ <b>횟수는 {@code penalty_rule.threshold}</b> 다 — ⚠️ 코드에 3을 박지 않았다.
     *
     * <h2>⚠️⚠️ 「교시별」의 뜻이 확정되지 않았다 — 지금은 <b>하루 단위</b>로 센다</h2>
     * 순찰 기록에 <b>교시가 없다.</b> 있는 것은 <b>순찰 회차({@code round_no}, 1~5)</b>이고
     * 스키마가 <b>{@code (날짜, 회차, 학생)} 유일</b>이라 <b>한 회차에 같은 학생을 3번 찍을
     * 수 없다.</b> 즉 <b>「같은 교시에 3회」가 회차 기준이면 애초에 불가능하다.</b>
     *
     * <p>★ 그래서 <b>그 날 졸음으로 찍힌 회차 수</b>를 센다. ⚠️ 디랩이 「교시별」로
     * <b>순찰 회차를 뜻한 것인지</b> 확인해야 하고, <b>교시를 뜻했다면 순찰 기록에
     * 교시를 더하고 멱등키도 {@code 학생:일자:교시:규칙} 으로 바꿔야 한다.</b>
     *
     * <p>★ 지금 멱등키는 <b>{@code 학생:일자:규칙}</b> 이라 <b>하루 한 번</b> 붙는다 —
     * 교시별이 확정되면 그 자리가 바뀐다.
     */
    PATROL,

    /**
     * ★ 사유 신청이 <b>승인</b>될 때 (디랩 1029 답변서 4-1).
     *
     * <p>조건값은 {@code AbsenceReasonType} 이름이다 —
     * {@code ABSENCE} · {@code LATE} · {@code EARLY_LEAVE} · {@code OUTING}.
     *
     * <h2>★★ 다른 트리거와 방향이 다르다</h2>
     * 나머지는 <b>학생 행위</b>(태깅·루틴)에 붙는데 이것은 <b>직원의 승인</b>에 붙는다.
     * 시트 원문이 *「직원이 사유 확인 후 승인 시」* 다 — 사유가 인정됐다는 사실 자체가
     * 벌점 사유다(무단보다 가볍게, 그러나 0 은 아니게).
     *
     * <p>⚠️ <b>반려·취소되면 거둬야 한다</b>({@code revokeAuto}) — 승인으로 붙은 것이라
     * 승인이 뒤집히면 근거가 사라진다.
     */
    APPROVAL,

    /**
     * 정기일정 미인정 (F-4.1-7).
     *
     * <p>등록 시각과 실제 출입이 30분 이상 어긋난 경우다. 조건값은
     * {@code NOT_RECOGNIZED} 하나뿐이라 규칙에서 조건을 비워두면 전부 걸린다.
     */
    REGULAR_SCHEDULE
}
