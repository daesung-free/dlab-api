package com.dlab.domain.scholarship.entity;

/**
 * 등급합에서 탐구를 어떻게 세는가 (0826 답변서).
 *
 * <p><b>★ 값으로 둔다.</b> 답변서가 <i>"해마다 탐구 1과목만 반영하기도 하고, 기준도
 * 전년도 난이도에 따라 변경된다"</i>고 명시했다. 코드에 박으면 해마다 클라이언트에
 * "올해는 1과목인가요 2과목인가요"를 다시 물어야 한다.
 */
public enum ElectiveMode {

    /**
     * 탐구 2과목 중 <b>좋은 쪽 1과목</b>만 센다. 평가원 기준 계열이 이 방식이다.
     *
     * <p>등급은 작을수록 좋으므로 <b>더 작은 값</b>을 고른다.
     */
    SINGLE,

    /**
     * 탐구 2과목의 <b>평균</b>. 수능 기준 계열이 이 방식이다.
     *
     * <p>⚠️ 평균이 3.5처럼 <b>정수가 아닐 수 있다.</b> 반올림해서 비교하면 경계에서
     * 한 칸씩 어긋나므로, 판정은 <b>등급합·임계값을 모두 2배한 정수</b>로 한다
     * (교습비 구간 비교를 정수 곱으로 하는 것과 같은 판단).
     */
    AVG2
}
