package com.dlab.domain.survey.entity;

/**
 * 설문 용도.
 *
 * <p>구조는 같고 화면 분류만 갈린다 — 가채점도 "과목별 자기 점수"라 숫자 문항 여러 개다.
 * 따로 만들면 배포·마감·집계를 두 번 짜게 된다.
 */
public enum SurveyType {

    /** 일반 설문. */
    GENERAL,

    /** 가채점 — 시험 직후 자기 점수 입력(F-4.6). */
    GRADE_INPUT,

    /**
     * 장학 동의서 (2026-10-13 디랩 회신 5-1).
     *
     * <p>디랩 요구가 <b>「구글 설문처럼 양식을 만들고 고치는 기능」</b>이라 일반 설문과
     * 같은 구조를 쓴다. 다른 점은 셋이다.
     * <ul>
     *   <li><b>대상이 사람 단위다</b> — 범위(전체·지점·반)가 아니라 직원이 장학을 부여한
     *       학생에게만 발송한다</li>
     *   <li><b>발송 / 열람 / 동의 / 제출 4단계</b>를 추적한다</li>
     *   <li><b>학생당 여러 장이 쌓인다</b> — 장학을 전환하면 기존 건이 취소되고 새 동의서가
     *       추가된다(확인 5)</li>
     * </ul>
     *
     * <p>★ <b>제출이 있으면 문항을 고칠 수 없다.</b> 고치면 이미 동의한 학생의 동의 내용이
     * 소급해서 바뀐다 — 약관을 버전으로 올리는 것과 같은 이유다. 복제해서 새로 만든다.
     */
    SCHOLARSHIP_CONSENT
}
