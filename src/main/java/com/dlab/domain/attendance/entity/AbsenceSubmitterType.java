package com.dlab.domain.attendance.entity;

/**
 * 사유 신청을 ★ <b>누가 냈는가</b> (디랩 1031 ③).
 *
 * <h2>★ 왜 구분이 필요한가</h2>
 * 관리자 화면에서 <b>「학부모 신청」이 구분돼 보여야 한다</b>(디랩 요청). 그리고
 * <b>승인 라우팅이 갈린다</b> — 우선 승인자가 「부모」일 때 <b>학부모가 낸 신청은
 * 낸 것이 곧 학부모 확인</b>이라 제출 즉시 승인된다.
 *
 * <p>⚠️ <b>{@code null} 이 있다</b> — 이 값이 생기기 전의 신청이다. 학생분과 데스크
 * 등록분이 섞여 있어 어느 쪽으로도 채우지 않았다.
 */
public enum AbsenceSubmitterType {

    /** 학생 앱. */
    STUDENT,

    /**
     * ★ 학부모 앱.
     *
     * <p>★ 우선 승인자가 「부모」면 <b>제출 즉시 승인</b>된다 — 낸 사람이 승인권자다.
     * ⚠️ 「담임」이면 <b>그대로 담임에게 간다.</b>
     */
    GUARDIAN,

    /** 데스크(직원) 직접 등록. */
    STAFF
}
