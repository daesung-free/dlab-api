package com.dlab.domain.meal.entity;

/**
 * 급식 주문 상태 — <b>등록비·급식 공통 결제 라이프사이클</b>(시트 3.데이터·업무로직 정의).
 *
 * <p><b>값을 새로 만들지 말 것.</b> 결제(E-3)가 붙기 전까지는 {@link #PENDING}에서
 * 움직이지 않는다. 지금 편한 값을 임의로 넣으면 결제가 붙을 때 전이가 어긋난다.
 *
 * <p>카드는 즉시 확정, 가상계좌는 10분 주기 스케줄러가 만료 처리한다.
 */
public enum MealOrderStatus {

    /** 신청됨. 결제 전이다 — 지금은 여기서 멈춘다. */
    PENDING,

    /** 가상계좌 발급됨. */
    ISSUED,

    /** 결제 완료 — 확정. */
    PAID,

    /** 취소 완료. */
    CANCELLED,

    /** 가상계좌 입금 기한 만료. */
    EXPIRED,

    /** 환불 완료. 취소와 분리한다 — 환불은 일할계산(I-26)이 걸린 별개 사건이다. */
    REFUNDED
}
