package com.dlab.domain.meal.entity;

/**
 * 취소 경로. 화면 목록에 컬럼으로 나온다.
 *
 * <p>정산 근거라서 물리 삭제하지 않고 이 값과 함께 남긴다.
 */
public enum CancelPath {

    /** 학생·학부모가 앱에서. 마감 D-n 전까지만 가능하고 PG 자동환불 대상이다. */
    APP,

    /** 관리자가 데스크에서. <b>기간 제한이 없다.</b> */
    DESK,

    /**
     * 급식 중단일 등록으로 인한 일괄 취소.
     *
     * <p><b>환불은 여기서 하지 않는다.</b> payment가 붙을 때 이 경로로 취소된 항목이
     * 곧 환불 대상 조회 지점이 된다 — 물리 삭제하면 그때 대상을 못 찾는다.
     */
    CLOSURE,

    /**
     * 퇴원·제적·수료로 인한 정리.
     *
     * <p>{@link #CLOSURE}와 나눈 이유는 <b>환불 근거가 다르기</b> 때문이다 —
     * 중단일은 학원 사정이라 전액 환불이고, 퇴원은 학원법 반환기준(I-26)을 탄다.
     * 한 값으로 묶으면 payment가 붙을 때 둘을 다시 갈라낼 수 없다.
     */
    WITHDRAWAL
}
