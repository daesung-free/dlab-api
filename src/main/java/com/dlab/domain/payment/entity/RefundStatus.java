package com.dlab.domain.payment.entity;

/** 환불 처리 상태. */
public enum RefundStatus {
    /** 집행 대기. 계좌 이체 대상이 여기 쌓인다 — 데스크가 매일 보는 목록이다. */
    PENDING,
    /** 집행 완료(카드 취소 성공, 또는 이체 완료 표시). */
    DONE,
    /** 집행 실패. <b>다시 걸 수 있다</b> — 유니크 인덱스가 이 상태는 비켜 간다. */
    FAILED,
    /**
     * 환불이 아니라 <b>추가 징수</b>다.
     *
     * <p>0820 규정의 「정상가 기준 차감」 때문에 할인받은 학생은 차감액이 납부액을
     * 넘을 수 있다. ★ <b>0 에서 자르지 않는다</b> — 자르면 받아야 할 돈이 사라지고
     * 데스크는 화면에서 그 사실을 알 방법이 없다.
     */
    ADDITIONAL_PAYMENT
}
