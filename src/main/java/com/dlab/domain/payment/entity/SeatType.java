package com.dlab.domain.payment.entity;

/**
 * 좌석 상품 구분. 가격이 여기서 갈린다.
 *
 * <p>좌석 <b>배정</b>(어느 자리에 앉는가)과는 다른 축이다 — 이건 "얼마짜리 상품인가"다.
 * 합치면 자리를 옮길 때마다 청구가 흔들린다.
 */
public enum SeatType {

    /** 일반좌석. */
    GENERAL,

    /**
     * 1인실. <b>분당·목동·대구에만 있고 지점마다 금액이 다르다</b> —
     * 교습비도 독서실비도 지점별이라 공통 가격을 둘 수 없다.
     */
    SINGLE
}
