package com.dlab.domain.payment.entity;

/**
 * 환불을 <b>어떻게 지급하는가</b> (디랩 10/12 회신 ②).
 *
 * <p>★ 결제 수단에 따라 갈린다 — 회신 원문: <i>"카드 결제 → 카드 취소 /
 * 가상계좌 입금 → 계좌 이체."</i>
 *
 * <p>⚠️ {@link BillingItemType.RefundMethod}(구간/일할)와 <b>다른 축</b>이다.
 * 저쪽은 <b>얼마를</b> 돌려줄지, 이쪽은 <b>어떻게</b> 돌려줄지다 — 이름이 비슷해
 * 섞기 쉬우므로 {@code RefundMethod} 를 쓰지 않았다.
 */
public enum RefundPayout {
    /** 카드 결제분 — PG 부분취소를 건다. */
    CARD_CANCEL,
    /**
     * 가상계좌 입금분 — <b>계좌 이체 대상으로 적재만</b> 한다.
     *
     * <p>우리가 이체를 실행하지 않는다. 이체는 사람이 은행에서 하고, 우리는
     * <b>누구에게 얼마를 보내야 하는지</b>를 목록으로 들고 있는다.
     */
    BANK_TRANSFER,
    /** 돌려줄 것이 없다 — 환불액 0, 또는 추가 징수(음수)다. */
    NONE,

    /**
     * ★★ <b>재결제 후 전체취소</b> (디랩 1029 7장).
     *
     * <p>디랩 원문: <b>「부분취소, 재결제 후 전체취소 모두 필요할 것 같습니다.
     * 지점이나 상황에 따라 골라서 사용할 수 있도록」</b>
     *
     * <h2>★★ 순서가 전부다</h2>
     * ① 재결제 금액으로 <b>결제 요청</b>을 학부모에게 보낸다 —
     * ★ <b>카드 정보를 보관하지 않으므로</b>(빌링키 없음) <b>서버가 혼자 결제할 수 없다.</b><br>
     * ② 재결제가 <b>완료된 것을 확인한 뒤</b> 기결제를 전체취소한다.
     *
     * <p>⚠️⚠️ <b>전체취소를 먼저 하지 말 것</b> — 학부모가 재결제를 안 하면
     * <b>받을 돈이 사라진다.</b>
     *
     * <p>⚠️ <b>가상계좌로 받은 기결제 건은 이 방식이 안 된다</b> — 계좌 이체
     * 환불이다(10/12 회신).
     */
    REPAY_AND_FULL_CANCEL
}
