package com.dlab.domain.notification.entity;

/**
 * 수동 발송에서 <b>제외된 사유</b>.
 *
 * <h2>★★ 이 값이 비면 담당자는 영영 모른다</h2>
 * 화면이 「30명에게 보냅니다」라고 했는데 28명에게 가면, 빠진 둘이 누구인지도 왜인지도
 * 알 방법이 없다. 그래서 미리보기가 <b>대상 수와 함께 제외 명단</b>을 돌려준다.
 *
 * <p>★ <b>사유를 자유 문자열로 두지 않는다.</b> 종류를 고정해야 화면이 묶어서 보여주고
 * ("연락처 없음 3명") 담당자가 무엇을 고쳐야 하는지 알 수 있다. 사람이 읽는 문장은
 * {@link #message()} 가 함께 준다 — 코드만 주면 화면마다 다른 말로 번역된다.
 */
public enum ManualBlockReason {

    /** 재원 상태가 아니다(퇴원·제적·수료). 미리보기를 열어 둔 사이에도 생긴다. */
    NOT_ENROLLED("재원 상태가 아닙니다."),

    /** 수신자에 해당하는 계정이 없다 — 학부모가 아직 앱에 가입하지 않은 경우가 대부분이다. */
    NO_ACCOUNT("알림을 받을 계정이 없습니다. 학부모 앱 가입이 필요합니다."),

    /** 계정은 있는데 연락처가 비어 있다. 알림톡은 번호로 나간다. */
    NO_PHONE("연락처가 등록되어 있지 않습니다."),

    /** 앱에서 이 유형의 알림을 끈 사람. 필수 알림은 끌 수 없다. */
    OPTED_OUT("이 알림 수신을 거부한 수신자입니다."),

    /** 다른 지점 학생. 지점 범위를 벗어난 선택은 발송하지 않고 드러낸다. */
    OTHER_ACADEMY("다른 지점 학생입니다."),
    /**
     * ★ 이관 기간 수신 허용목록에 없는 번호.
     *
     * <p>실제 번호를 다 넣어 두고 검증하는 동안 학부모에게 나가지 않게 막는 장치다
     * ({@code notification.allowlist}). ⚠️ 이관이 끝나면 비워야 한다 —
     * 켠 채로 두면 <b>그 번호들만 알림을 받고</b> 화면에는 제외로만 남는다.
     */
    NOT_IN_ALLOWLIST("이관 기간 수신 허용목록에 없는 번호입니다.");

    private final String message;

    ManualBlockReason(String message) {
        this.message = message;
    }

    public String message() {
        return message;
    }
}
