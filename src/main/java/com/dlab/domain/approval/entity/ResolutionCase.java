package com.dlab.domain.approval.entity;

/**
 * 승인이 어떤 상황에서 이뤄졌는지. 케이스별로 학부모에게 나가는 안내 문구가 달라야 한다.
 *
 * <p><b>아래 2·3번을 절대 같은 문구로 통일하지 말 것</b> — 학부모 입장에서 전혀 다른 상황이고,
 * 합치면 "왜 시간 남았는데 담임이 승인했지" 하는 혼란이 생긴다.
 */
public enum ResolutionCase {
    /** 1. 타임아웃 전 학부모 승인 — 정상 흐름 */
    PARENT_IN_TIME,
    /**
     * 1-b. <b>타임아웃이 지난 뒤</b> 학부모가 승인 — 늦었지만 학부모가 처리했다.
     *
     * <p>전에는 이것도 {@link #PARENT_IN_TIME} 이었다. 승인자가 학부모면 시각을 보지
     * 않았기 때문인데, 그러면 <b>열 시간 뒤 승인도 "시간 내"로 기록된다.</b> 담임 쪽은
     * 전후를 가르면서 학부모만 한 칸인 것도 어긋난다.
     *
     * <p><b>문구는 {@link #PARENT_IN_TIME} 과 같다.</b> 학부모가 승인했다는 사실은 같고,
     * 늦었다는 것을 굳이 본인에게 알릴 이유가 없다 — 나누는 것은 기록이지 안내가 아니다.
     *
     * <p>필요한 이유는 통계다. "학부모 무응답으로 담임이 처리한 비율" 을 보려면 늦게라도
     * 학부모가 처리한 건이 정상 응답과 섞이면 안 되고, 타임아웃 10분이 운영에 맞는지도
     * 이 숫자로 판단한다.
     */
    PARENT_AFTER_TIMEOUT,
    /** 2. 무응답으로 타임아웃이 지난 뒤 담당선생님이 승인 → "승인 시간이 지나 담임이 승인했습니다" */
    STAFF_AFTER_TIMEOUT,
    /** 3. 타임아웃 전인데 담당선생님이 먼저 승인 → "승인 시간이 남았지만 담임이 먼저 승인 처리했습니다" */
    STAFF_BEFORE_TIMEOUT,
    /**
     * 4. <b>우선 승인자가 직원</b>이라 직원이 승인 (0803 답변서).
     *
     * <p>{@link #STAFF_BEFORE_TIMEOUT}과 합치면 안 된다 — 그쪽은 학부모가 기다리는 중에
     * 담임이 끼어든 상황이고, 이쪽은 <b>애초에 학부모가 승인자가 아닌</b> 상황이다.
     * "시간이 남았지만 담임이 먼저 승인했습니다"가 학부모에게 나가면 이상하다.
     */
    STAFF_PRIMARY,

    /**
     * 5. <b>관리자가 데스크에서 대신 처리</b> (F-4.1-6).
     *
     * <p>담임도 아니고 우선 승인자도 아니다. 위 넷 중 어느 문구를 써도 학부모에게
     * 사실과 다른 안내가 나간다 — "담임이 승인했습니다"라고 하면 담임은 이 건을
     * 본 적도 없다.
     */
    ADMIN_PROXY
}
