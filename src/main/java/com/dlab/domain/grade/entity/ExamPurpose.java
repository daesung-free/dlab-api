package com.dlab.domain.grade.entity;

/**
 * 성적 양식의 용도.
 *
 * <h2>★ 왜 나누는가</h2>
 * 입학 전 성적과 디랩에서 본 시험이 <b>같은 회차 행을 쓰고 있었다.</b> N수생의 "작년 6평"
 * (가입 때 입력)과 "올해 6평"(연구소 파일)이 둘 다 {@code N_SU · JUNE} 이라, 올해 6평을
 * 업로드하면 <b>학생이 넣고 선생님이 대조까지 끝낸 작년 6평이 지워졌다</b> — 업로드는 그
 * 회차 점수를 교체하기 때문이다.
 *
 * <p>앱 시안도 둘을 나눠 보여준다(「입학 때 입력한 성적」 / 「디랩 모의고사」).
 */
public enum ExamPurpose {
    /** 입학 전 성적 — 학생이 가입 때 입력하고 선생님이 성적표로 대조한다 */
    ADMISSION,
    /** 디랩에서 본 시험 — 연구소가 보낸 파일을 학원이 올린다 */
    ACADEMY
}
